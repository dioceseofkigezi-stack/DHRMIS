/**
 * DHRMIS - Audit Service
 * Central audit logging, audit policy enforcement, and audit query utilities
 */

import { supabase } from "@/core/config";
import type { AuditAction, AuditResult, SecurityEvent, SensitiveReadLog } from "@/types";
import { AUDIT_CONFIG } from "./config";

export interface LogActionInput {
  action: AuditAction;
  module: string;
  recordId?: string;
  recordType?: string;
  employeeId?: string;
  scopeIds?: string[];
  ipAddress?: string;
  deviceInfo?: string;
  userAgent?: string;
  result: AuditResult;
  beforeValues?: Record<string, unknown>;
  afterValues?: Record<string, unknown>;
  purpose?: string;
  context?: string;
  sessionId?: string;
}

const getAuthenticatedUserId = async (): Promise<string | null> => {
  if (!supabase) throw new Error("Supabase is not configured.");
  const { data: { user }, error } = await supabase.auth.getUser();
  if (error) throw error;
  if (!user) return null;
  return user.id;
};

export const auditService = {
  async logAction(_input: LogActionInput) {
    if (!AUDIT_CONFIG.enableAuditLog) return;
    if (!supabase) throw new Error("Supabase is not configured.");
    throw new Error("Audit records are generated by database triggers and cannot be written directly.");
  },

  async logSensitiveRead({
    userId,
    employeeId,
    recordId,
    recordType,
    dataCategory,
    purpose,
    scopeIds,
    sessionId,
    ipAddress,
    deviceInfo,
  }: {
    userId: string;
    employeeId?: string;
    recordId?: string;
    recordType: string;
    dataCategory: SensitiveReadLog["dataCategory"];
    purpose: string;
    scopeIds?: string[];
    sessionId?: string;
    ipAddress?: string;
    deviceInfo?: string;
  }) {
    if (!AUDIT_CONFIG.enableSensitiveReadLogging) return;
    if (!supabase) throw new Error("Supabase is not configured.");
    const authenticatedUserId = await getAuthenticatedUserId();
    if (!authenticatedUserId || authenticatedUserId !== userId) {
      throw new Error("Sensitive-read logs can only be recorded for the authenticated user.");
    }

    const audit = {
      user_id: userId,
      employee_id: employeeId,
      record_id: recordId,
      record_type: recordType,
      data_category: dataCategory,
      purpose,
      scope_ids: scopeIds,
      session_id: sessionId,
      ip_address: ipAddress,
      device_info: deviceInfo,
    };

    const { error } = await supabase.from("sensitive_read_log").insert(audit);
    if (error) throw error;
  },

  async logSecurityEvent({
    userId,
    eventType,
    severity,
    component,
    description,
    ipAddress,
    userAgent,
    details,
    acknowledged,
    acknowledgedBy,
    resolved,
  }: {
    userId?: string;
    eventType: SecurityEvent["eventType"];
    severity: SecurityEvent["severity"];
    component: string;
    description: string;
    ipAddress?: string;
    userAgent?: string;
    details?: Record<string, unknown>;
    acknowledged?: boolean;
    acknowledgedBy?: string;
    resolved?: boolean;
  }) {
    if (!AUDIT_CONFIG.enableSecurityEventLogging) return;
    if (!supabase) throw new Error("Supabase is not configured.");

    const audit = {
      user_id: userId,
      event_type: eventType,
      severity,
      component,
      description,
      ip_address: ipAddress,
      user_agent: userAgent,
      details: details || null,
      acknowledged: acknowledged ?? false,
      acknowledged_by: acknowledgedBy,
      resolved: resolved ?? false,
    };

    const { error } = await supabase.from("security_event").insert(audit);
    if (error) throw error;
  },

  isMakerCheckerRequired(action: AuditAction): boolean {
    return AUDIT_CONFIG.requireMakerChecker.includes(action);
  },

  isSensitiveAction(action: AuditAction): boolean {
    return AUDIT_CONFIG.sensitiveActions.includes(action);
  },
};

export const enforceMakerChecker = async (
  makerId: string,
  approverId: string,
  module: string,
  recordId: string,
  action: AuditAction,
): Promise<void> => {
  if (AUDIT_CONFIG.requireMakerChecker.includes(action) && makerId === approverId) {
    throw new Error(`Maker cannot approve their own ${action} on ${module}/${recordId}`);
  }
};

export const encryptForLogging = (data: unknown): string => {
  if (data === undefined) throw new Error("A value is required.");
  return "[REDACTED]";
};
